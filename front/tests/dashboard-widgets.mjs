import {chromium} from '@playwright/test'
import {createServer} from 'vite'
import assert from 'node:assert/strict'
const server=await createServer({configLoader:'runner',server:{host:'127.0.0.1',port:0,strictPort:false}})
await server.listen()
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/dashboard-widgets-fixture.html`)
  assert.equal(await page.locator('.widget-tools').count(),0)
  await page.getByRole('button',{name:'위젯 편집',exact:true}).click()
  await page.mouse.click(2,2)
  assert.equal(await page.getByRole('region',{name:'추가할 위젯 목록',exact:true}).count(),0)
  await page.getByRole('button',{name:'위젯 목록',exact:true}).click()
  await page.getByRole('region',{name:'추가할 위젯 목록',exact:true}).getByRole('button',{name:'최근 이벤트 제거',exact:true}).click()
  assert.equal(await page.getByRole('article',{name:'최근 이벤트',exact:true}).count(),0)
  await page.getByRole('button',{name:'최근 이벤트 추가',exact:true}).click()
  assert.equal(await page.getByRole('article',{name:'최근 이벤트',exact:true}).count(),1)
  const calendar = page.getByRole('article',{name:'캘린더·일정',exact:true})
  assert.equal(await calendar.evaluate(element=>getComputedStyle(element).display),'flex')
  const calendarHeader=await calendar.locator('header').boundingBox(),calendarNav=await calendar.locator('.widget-calendar-nav').boundingBox(),calendarGrid=await calendar.locator('.widget-calendar').boundingBox()
  assert(calendarNav.y>=calendarHeader.y+calendarHeader.height)
  assert(calendarGrid.y>=calendarNav.y+calendarNav.height)
  assert.equal(await calendar.locator('.widget-calendar').evaluate(element=>getComputedStyle(element).gridTemplateColumns.split(' ').length),7)
  await page.getByRole('button',{name:'업무 체크리스트 추가',exact:true}).click()
  assert.match(await page.getByRole('article',{name:'업무 체크리스트',exact:true}).getAttribute('class'),/notification-arrival-glow/)
  await page.locator('.widget-library-item').filter({has:page.getByRole('button',{name:'업무 메모 추가',exact:true})}).dragTo(page.getByRole('article',{name:'지하차도 현황',exact:true}))
  await page.getByRole('article',{name:'업무 메모',exact:true}).waitFor()
  const handle=page.getByRole('button',{name:'업무 메모 크기 조절',exact:true})
  await handle.scrollIntoViewIfNeeded()
  const grip=await handle.boundingBox()
  await page.mouse.move(grip.x+grip.width/2,grip.y+grip.height/2)
  await page.mouse.down()
  await page.mouse.move(grip.x+5000,grip.y+160,{steps:8})
  await page.mouse.up()
  const resized=await page.getByRole('article',{name:'업무 메모',exact:true}).boundingBox(),gridBounds=await page.locator('.personal-widget-grid').boundingBox()
  assert(resized.x+resized.width<=gridBounds.x+gridBounds.width+1)
  assert(Math.abs((resized.height+16)%80)<1)
  const savedSpan=await page.getByRole('article',{name:'업무 메모',exact:true}).getAttribute('style')
  await page.mouse.click(2,2)
  await page.getByRole('button',{name:'편집 완료',exact:true}).click()
  assert.equal(await page.locator('.widget-tools').count(),0)
  assert.equal(await page.getByRole('region',{name:'추가할 위젯 목록',exact:true}).count(),0)
  await page.getByRole('textbox',{name:'새 일정',exact:true}).fill('현장 점검')
  await page.getByRole('article',{name:'캘린더·일정',exact:true}).getByRole('button',{name:'추가',exact:true}).click()
  await page.getByRole('textbox',{name:'새 업무',exact:true}).fill('차단기 확인')
  await page.getByRole('article',{name:'업무 체크리스트',exact:true}).getByRole('button',{name:'추가',exact:true}).click()
  await page.getByRole('checkbox',{name:'차단기 확인',exact:true}).check()
  await page.getByRole('textbox',{name:'업무 메모',exact:true}).fill('야간 점검 인계')
  await page.reload()
  assert.equal(await page.getByRole('article',{name:'업무 메모',exact:true}).getAttribute('style'),savedSpan)
  assert.equal(await page.getByRole('textbox',{name:'업무 메모',exact:true}).inputValue(),'야간 점검 인계')
  assert(await page.getByRole('checkbox',{name:'차단기 확인',exact:true}).isChecked())
  await page.getByRole('button',{name:'위젯 편집',exact:true}).click()
  await page.mouse.click(2,2)
  await page.getByRole('button',{name:'업무 메모 크기 조절',exact:true}).press('ArrowDown')
  await page.getByRole('button',{name:'지하차도 현황 위젯 제거',exact:true}).click()
  await page.getByRole('button',{name:'취소',exact:true}).click()
  assert.equal(await page.getByRole('article',{name:'업무 메모',exact:true}).getAttribute('style'),savedSpan)
  assert.equal(await page.getByRole('article',{name:'지하차도 현황',exact:true}).count(),1)
  await page.getByRole('button',{name:'위젯 편집',exact:true}).click()
  await page.mouse.click(2,2)
  await page.getByRole('button',{name:'기본 배치',exact:true}).click()
  await page.mouse.click(2,2)
  await page.getByRole('button',{name:'편집 완료',exact:true}).click()
  assert.equal(await page.getByRole('article',{name:'업무 메모',exact:true}).count(),0)
  await page.getByRole('button',{name:'위젯 편집',exact:true}).click()
  await page.getByRole('button',{name:'업무 메모 추가',exact:true}).click()
  await page.mouse.click(2,2)
  await page.getByRole('button',{name:'편집 완료',exact:true}).click()
  assert.equal(await page.getByRole('textbox',{name:'업무 메모',exact:true}).inputValue(),'야간 점검 인계')
  for(const width of [1440,390]){await page.setViewportSize({width,height:1000});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)}
  assert.deepEqual(errors,[])
  console.log('통과: 편집 모드·드래그 추가·취소·기본 배치·저장 복원·모바일 배치')
}finally{await browser.close();await server.close()}
