  await walker.clock.install()
  await walker.route('**/api/**',r=>r.fulfill({json:{success:true,data:null}}))
  await walker.goto(`http://127.0.0.1:${server.httpServer.address().port}/c-notice`)
  const pet=walker.locator('#public-chat-launcher')
  await pet.waitFor()
  assert.equal(await pet.locator('.chat-mascot-reaction').textContent(),'…','idle mascot shows dots')
  const idlePosition=await pet.boundingBox()
  await walker.clock.runFor(7500)
  assert(!(await pet.getAttribute('class')).includes('is-walking'),'idle mascot stays still')
  const walkingPosition=await pet.boundingBox()
  assert(Math.abs(walkingPosition.x-idlePosition.x)<1,'idle position does not change')
  await walker.mouse.move(walkingPosition.x+30,walkingPosition.y+30)
  await walker.mouse.down()
  await walker.mouse.move(walkingPosition.x-50,walkingPosition.y+30)
  assert((await pet.getAttribute('class')).includes('is-walking'),'dragging activates walking')
  assert((await pet.getAttribute('class')).includes('faces-left'),'leftward drag faces left')
